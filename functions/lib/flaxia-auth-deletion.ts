import { deleteAccount } from './account-deletion.ts';
import { deleteAuthAccount } from './flaxia-auth.ts';

const OPERATION = /^[A-Za-z0-9_-]{43}$/;
export async function deletionOperationHash(operation: string): Promise<string | null> {
  if (!OPERATION.test(operation)) return null;
  const bytes = new Uint8Array(await crypto.subtle.digest('SHA-256', new TextEncoder().encode(operation)));
  return btoa(String.fromCharCode(...bytes))
    .replaceAll('+', '-')
    .replaceAll('/', '_')
    .replaceAll('=', '');
}

type Job = { user_id: string; grant_token: string; proof_json: string; state: 'pending' | 'approved' };
type Result = 'ok' | 'denied' | 'unavailable' | 'not_found';

// The operation token is a 256-bit capability generated by the browser before
// the first request. The receipt remains after the user and session are gone.
export async function resumeAuthDeletion(
  env: Env,
  operation: string,
  deleteLocal: typeof deleteAccount = deleteAccount,
): Promise<Result> {
  const hash = await deletionOperationHash(operation);
  if (!hash) return 'not_found';
  try {
    if (await env.DB.prepare('SELECT 1 FROM flaxia_auth_deletion_receipts WHERE operation_hash = ?').bind(hash).first())
      return 'ok';
    const job = await env.DB.prepare(
      'SELECT user_id, grant_token, proof_json, state FROM flaxia_auth_deletion_jobs WHERE operation_hash = ?',
    )
      .bind(hash)
      .first<Job>();
    if (!job) return 'not_found';
    if (job.state === 'pending') {
      const proof = JSON.parse(job.proof_json) as { challenge_id: string; A: string; M1: string };
      const result = await deleteAuthAccount(
        env as { AUTH_SERVICE?: Fetcher },
        operation,
        job.grant_token,
        job.user_id,
        proof,
      );
      if (result !== 'ok') return result;
      await env.DB.prepare(
        "UPDATE flaxia_auth_deletion_jobs SET state = 'approved' WHERE operation_hash = ? AND user_id = ? AND state = 'pending'",
      )
        .bind(hash, job.user_id)
        .run();
    }
    await deleteLocal(env, job.user_id, hash);
    return 'ok';
  } catch (error) {
    console.error('Auth account deletion failed', error);
    // Another request can have completed the same operation concurrently.
    try {
      if (
        await env.DB.prepare('SELECT 1 FROM flaxia_auth_deletion_receipts WHERE operation_hash = ?').bind(hash).first()
      )
        return 'ok';
    } catch {
      /* preserve retryability */
    }
    return 'unavailable';
  }
}
