import { deleteAccount } from './account-deletion.ts';
import { cancelAuthCredentialHash, deleteAuthAccount } from './flaxia-auth.ts';
import { resumeDirectEmailChange } from './flaxia-direct-email.ts';

const OPERATION = /^[A-Za-z0-9_-]{43}$/;
export async function deletionOperationHash(operation: string): Promise<string | null> {
  if (!OPERATION.test(operation)) return null;
  const bytes = new Uint8Array(await crypto.subtle.digest('SHA-256', new TextEncoder().encode(operation)));
  return btoa(String.fromCharCode(...bytes))
    .replaceAll('+', '-')
    .replaceAll('/', '_')
    .replaceAll('=', '');
}

type Job = { user_id: string; grant_token: string; proof_json: string; state: 'pending' | 'approved' };
type Result = 'ok' | 'denied' | 'unavailable' | 'not_found';

// Deletion must win over unfinished profile transitions. They are either
// cancelled at Auth or already committed; either way their local rows would
// otherwise trip a guard before the deletion job can be recorded.
export async function settleDeletionTransitions(
  env: Env,
  grant: string,
  userId: string,
): Promise<'ok' | 'unavailable'> {
  if (!OPERATION.test(grant)) return 'unavailable';
  const authEnv = env as { AUTH_SERVICE?: Fetcher };
  try {
    const email = await env.DB.prepare('SELECT 1 FROM flaxia_direct_email_changes WHERE user_id = ?')
      .bind(userId)
      .first();
    if (email) {
      const result = await resumeDirectEmailChange(env, grant, userId, true);
      if (result === 'unavailable') return 'unavailable';
      await env.DB.prepare('DELETE FROM flaxia_direct_email_changes WHERE user_id = ?').bind(userId).run();
    }

    const active = await env.DB.prepare(
      `SELECT operation_hash FROM flaxia_direct_vault_changes
       WHERE user_id = ? AND state NOT IN ('committed', 'cancelled')
       UNION ALL
       SELECT operation_hash FROM flaxia_auth_credential_jobs
       WHERE user_id = ? AND state NOT IN ('committed', 'cancelled')`,
    )
      .bind(userId, userId)
      .all<{ operation_hash: string }>();
    for (const row of active.results ?? []) {
      if ((await cancelAuthCredentialHash(authEnv, row.operation_hash, grant, userId)) === 'unavailable')
        return 'unavailable';
    }

    await env.DB.batch([
      env.DB.prepare('DELETE FROM flaxia_direct_vault_changes WHERE user_id = ?').bind(userId),
      env.DB.prepare('DELETE FROM flaxia_auth_credential_jobs WHERE user_id = ?').bind(userId),
      env.DB.prepare('DELETE FROM flaxia_auth_purge_in_progress WHERE user_id = ?').bind(userId),
      // A valid deletion proof means Auth still holds this identity, so an old
      // operation cannot have completed. Replacing it lets a browser that lost
      // its operation token retry instead of being blocked by user_id UNIQUE.
      env.DB.prepare('DELETE FROM flaxia_auth_deletion_jobs WHERE user_id = ?').bind(userId),
      env.DB.prepare('DELETE FROM flaxia_direct_deletion_jobs WHERE user_id = ?').bind(userId),
    ]);
    return 'ok';
  } catch {
    return 'unavailable';
  }
}

// The operation token is a 256-bit capability generated by the browser before
// the first request. The receipt remains after the user and session are gone.
export async function resumeAuthDeletion(
  env: Env,
  operation: string,
  deleteLocal: typeof deleteAccount = deleteAccount,
): Promise<Result> {
  const hash = await deletionOperationHash(operation);
  if (!hash) return 'not_found';
  try {
    if (await env.DB.prepare('SELECT 1 FROM flaxia_auth_deletion_receipts WHERE operation_hash = ?').bind(hash).first())
      return 'ok';
    const job = await env.DB.prepare(
      'SELECT user_id, grant_token, proof_json, state FROM flaxia_auth_deletion_jobs WHERE operation_hash = ?',
    )
      .bind(hash)
      .first<Job>();
    if (!job) return 'not_found';
    if (job.state === 'pending') {
      const proof = JSON.parse(job.proof_json) as { challenge_id: string; A: string; M1: string };
      const result = await deleteAuthAccount(
        env as { AUTH_SERVICE?: Fetcher },
        operation,
        job.grant_token,
        job.user_id,
        proof,
      );
      if (result !== 'ok') return result;
      await env.DB.prepare(
        "UPDATE flaxia_auth_deletion_jobs SET state = 'approved' WHERE operation_hash = ? AND user_id = ? AND state = 'pending'",
      )
        .bind(hash, job.user_id)
        .run();
    }
    await deleteLocal(env, job.user_id, hash);
    return 'ok';
  } catch (error) {
    console.error('Auth account deletion failed', error);
    // Another request can have completed the same operation concurrently.
    try {
      if (
        await env.DB.prepare('SELECT 1 FROM flaxia_auth_deletion_receipts WHERE operation_hash = ?').bind(hash).first()
      )
        return 'ok';
    } catch {
      /* preserve retryability */
    }
    return 'unavailable';
  }
}
