// Post-SvelteKit build steps: the adapter owns dist/, so these run after it.
import { copyFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dist = 'dist';
const index = join(dist, 'index.html');
if (!existsSync(index)) throw new Error('dist/index.html missing — did vite build run?');

if (existsSync('export-popup.html')) copyFileSync('export-popup.html', join(dist, 'export-popup.html'));

// adapter-static may clear dist/ after the Vite plugin's closeBundle, so the
// docs manifest is written again here (the dev middleware uses the same code).
import { writeDocsManifest } from './docs-manifest.mjs';

writeDocsManifest(join(dist, 'docs'));

const html = readFileSync(index, 'utf-8');
const headEnd = html.indexOf('</head>');
if (headEnd === -1) throw new Error('dist/index.html has no </head>');
const head = html.slice(0, headEnd);
const tags = [...(head.match(/<link[\s\S]*?>/g) ?? []), ...(head.match(/<script[\s\S]*?<\/script>/g) ?? [])].filter(
  (tag) => tag.includes('/_app/') || tag.includes('/assets/'),
);
writeFileSync(
  'functions/lib/ssr-head.generated.ts',
  `// Auto-generated by vite build — do not edit manually\nexport const SPA_HEAD_TAGS: string = ${JSON.stringify(tags.join('\n  '))};\n`,
);
console.log('Post-build: copied export popup and generated SSR head tags');

// F2: derive every inline-script hash from the actual build output and keep
// both CSP copies in sync. Unknown existing hashes (the retired legacy ZIP
// wrapper) are preserved until F8 removes that script.
import { createHash } from 'node:crypto';

const hashBody = (body) => `'sha256-${createHash('sha256').update(body).digest('base64')}'`;
const inlineBodies = (file) => {
  if (!existsSync(file)) return [];
  const source = readFileSync(file, 'utf-8');
  return [...source.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)]
    .filter(([, attrs]) => !/\bsrc\s*=/.test(attrs) && !/application\/ld\+json/i.test(attrs))
    .map(([, , body]) => body);
};

const generated = new Set();
for (const file of [index, join(dist, 'export-popup.html')]) {
  for (const body of inlineBodies(file)) generated.add(hashBody(body));
}
const { ADSENSE_INLINE_BOOTSTRAP } = await import('../src/lib/adsense-bootstrap.ts');
const { FLASH_PLAYER_BOOTSTRAP } = await import('../src/lib/flash-player-document.ts');
generated.add(hashBody(ADSENSE_INLINE_BOOTSTRAP));
generated.add(hashBody(FLASH_PLAYER_BOOTSTRAP));

// Only the retired ZIP-wrapper bootstrap has no source left to derive from.
// Everything else must come from the current build, otherwise the allowlist
// grows forever with stale SvelteKit hashes and hides real regressions.
const LEGACY_HASHES = ["'sha256-9jpcqwJpr7kicF5b0vRUbAJtyA6CqjotdcnTjIv8i4U='"];
const hashes = [...generated, ...LEGACY_HASHES.filter((item) => !generated.has(item))];

const headersFile = 'public/_headers';
const headers = readFileSync(headersFile, 'utf-8');

const securityFile = 'functions/lib/ssr-security-headers.ts';
const security = readFileSync(securityFile, 'utf-8');
const arrayStart = security.indexOf('const CSP_SCRIPT_HASHES = [');
const arrayEnd = security.indexOf("].join(' ');", arrayStart);
if (arrayStart === -1 || arrayEnd === -1) throw new Error('CSP_SCRIPT_HASHES block not found');
const newArray =
  'const CSP_SCRIPT_HASHES = [\n' +
  '  // Auto-generated by scripts/postbuild.mjs — do not edit manually\n' +
  hashes.map((item) => `  ${JSON.stringify(item)},`).join('\n') +
  '\n';
writeFileSync(securityFile, security.slice(0, arrayStart) + newArray + security.slice(arrayEnd));

const hashRun = /'sha256-[^']+'(?:\s+'sha256-[^']+')*/;
const cspLine = /^(\s*Content-Security-Policy: .+)$/m;
const match = headers.match(cspLine);
if (!match) throw new Error('Content-Security-Policy header not found in public/_headers');
writeFileSync(headersFile, headers.replace(cspLine, match[1].replace(hashRun, hashes.join(' '))));
copyFileSync(headersFile, join(dist, '_headers'));
console.log(`Post-build: refreshed ${hashes.length} CSP script hashes`);
