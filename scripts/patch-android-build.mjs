import { execSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, readFileSync, unlinkSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { patchAndroidVersionCode, androidVersionCode as versionCodeFromReleaseTag } from './android-version-code.mjs';

// launcher icons (generate from assets/icon.png via capacitor-assets)
try {
  execSync('npx capacitor-assets generate --android --assetPath assets', {
    stdio: 'pipe',
    timeout: 30000,
  });
  console.log('Generated Android launcher icons');
} catch (err) {
  console.error('WARNING: Failed to generate launcher icons from assets/icon.png.');
  console.error('App will use default Capacitor icons. Ensure @capacitor/assets and its');
  console.error('dependencies (sharp) are properly installed.');
  console.error(`Error: ${err.stderr?.toString().trim() || err.message}`);
}

// RELEASE_TAG must be converted to ANDROID_VERSION_CODE by the build workflow.
const releaseTag = process.env.RELEASE_TAG ?? process.env.GITHUB_REF_NAME;
const androidVersionCode = releaseTag ? versionCodeFromReleaseTag(releaseTag) : process.env.ANDROID_VERSION_CODE;

// Generate notification small icon (white leaf silhouette) for Android status bar
try {
  execSync('node scripts/generate-notification-icon.mjs', {
    stdio: 'pipe',
    timeout: 15000,
  });
  const notifIconPath = resolve('android/app/src/main/res/drawable/ic_stat_flaxia.png');
  if (!existsSync(notifIconPath)) {
    throw new Error(`expected ${notifIconPath} to be generated`);
  }
  console.log('Generated notification small icon (ic_stat_flaxia.png)');
} catch (err) {
  console.error('ERROR: Failed to generate notification icon.');
  console.error('Android would fall back to the launcher icon (white square) in the status bar.');
  console.error(`Error: ${err.stderr?.toString().trim() || err.message}`);
  process.exit(1);
}

// Remove the emoji-face vector generated by cap add android (drawable-v24)
// which overrides the proper Flaxia launcher foreground from assets/icon.png.
const faceIconPath = resolve('android/app/src/main/res/drawable-v24/ic_launcher_foreground.xml');
if (existsSync(faceIconPath)) {
  unlinkSync(faceIconPath);
  console.log('Removed drawable-v24/ic_launcher_foreground.xml (emoji face)');
}

// Mirror the generated mipmap foreground PNG into drawable/ so launchers that
// reference R.drawable.ic_launcher_foreground directly still resolve it.
// (The notification small icon is ic_stat_flaxia.png, generated above.)
const drawableDir = resolve('android/app/src/main/res/drawable');
const foregroundPng = resolve(drawableDir, 'ic_launcher_foreground.png');
if (!existsSync(foregroundPng)) {
  mkdirSync(drawableDir, { recursive: true });
  const mipmapHdpi = resolve('android/app/src/main/res/mipmap-hdpi/ic_launcher_foreground.png');
  if (existsSync(mipmapHdpi)) {
    copyFileSync(mipmapHdpi, foregroundPng);
    console.log('Copied ic_launcher_foreground.png to drawable/');
  }
}

const buildGradlePath = resolve('android/app/build.gradle');
if (!existsSync(buildGradlePath)) {
  console.log('build.gradle not found — skipping patches');
  process.exit(0);
}

let content = readFileSync(buildGradlePath, 'utf8');

// Fail closed if a release tag could not be converted into a versionCode.
if (releaseTag && !androidVersionCode) {
  throw new Error(`No Android versionCode is available for ${releaseTag}`);
}
if (androidVersionCode) {
  const versionCode = Number(androidVersionCode);
  content = patchAndroidVersionCode(content, versionCode);
  console.log(`Set Android defaultConfig versionCode ${versionCode}`);
}

// Leave Gradle's default APK/AAB filenames unchanged.

const keystoreFile = process.env.ANDROID_KEYSTORE_FILE;
const keystorePassword = process.env.ANDROID_KEYSTORE_PASSWORD;
const keyAlias = process.env.ANDROID_KEY_ALIAS;
const keyPassword = process.env.ANDROID_KEY_PASSWORD;

// A release must never publish an unsigned bundle. Local debug builds may omit
// signing credentials, but tagged/explicit release builds fail closed.
const requireSigning = Boolean(process.env.RELEASE_TAG) || process.env.REQUIRE_ANDROID_SIGNING === '1';
if (
  requireSigning &&
  (!keystoreFile ||
    !keystorePassword ||
    !keyAlias ||
    !keyPassword ||
    !existsSync(keystoreFile) ||
    readFileSync(keystoreFile).byteLength === 0)
) {
  throw new Error('Android release signing requires all four ANDROID_KEY* variables and a non-empty keystore file');
}

// #106: Groovy single-quoted strings treat backslash as the escape
// character, so escape backslashes first — otherwise a trailing backslash
// would escape the closing quote and corrupt the build file.
const gradleEscape = (s) => s.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
if (keystoreFile && keystorePassword && keyAlias && keyPassword) {
  content = content.replace(
    /android\s*\{/,
    `android {
    signingConfigs {
        release {
            storeFile file('${gradleEscape(keystoreFile)}')
            storePassword '${gradleEscape(keystorePassword)}'
            keyAlias '${gradleEscape(keyAlias)}'
            keyPassword '${gradleEscape(keyPassword)}'
        }
    }`,
  );

  content = content.replace(
    /(buildTypes\s*\{[^}]*?release\s*\{)/,
    '$1\n            signingConfig signingConfigs.release',
  );
  console.log('Signing config patched into build.gradle');
} else {
  console.log('Missing signing env vars — skipping signing patch');
}

writeFileSync(buildGradlePath, content);
